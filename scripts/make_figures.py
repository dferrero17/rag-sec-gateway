#!/usr/bin/env python3
"""Generate the paper's results artifacts from the benchmark output.

  figures/asr-heatmap.pdf   single-panel vulnerable-mode ASR heatmap
                            (scenarios x models); the gateway zeroes every cell,
                            so the secure panel is omitted and noted in prose.
  tables/factorial.tex      per-scenario factorial: ASR under guardrails-off,
                            hardened-prompt-only, structural (P2,P5), and all five,
                            so the reader sees which lever closes which attack.

Usage:
  python3 scripts/make_figures.py --summary ../rag-sec/results_full/summary.json \
      --factorial ../rag-sec/results_full/factorial.jsonl --tables tables --figures figures

Table generation is pure stdlib; the heatmap needs matplotlib.
"""

import argparse
import json
import os

MODELS = ["stub", "llama31-8b", "qwen25-7b", "mistral-7b", "gemma3-12b", "phi4-14b"]
SCEN = ["S1", "S2", "S3", "S4", "S5", "S6"]
MODEL_LABEL = {"stub": "Stub", "llama31-8b": "Llama 3.1 8B", "qwen25-7b": "Qwen2.5 7B",
               "mistral-7b": "Mistral 7B", "gemma3-12b": "Gemma 3 12B", "phi4-14b": "Phi-4 14B"}
SCEN_LABEL = {"S1": "S1 direct inj.", "S2": "S2 indirect inj.", "S3": "S3 data leak",
              "S4": "S4 tool abuse", "S5": "S5 prompt leak", "S6": "S6 bad output"}


def make_heatmap(summary_path, out_dir):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    rows = json.load(open(summary_path))["by_model_scenario_mode"]
    asr = {(r["model_label"], r["scenario"], r["mode"]): r["attack_success_rate"] for r in rows}
    data = [[(asr.get((m, s, "vulnerable")) or 0.0) for m in MODELS] for s in SCEN]

    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "asr-heatmap.pdf")
    fig, ax = plt.subplots(figsize=(6.4, 3.0), constrained_layout=True)
    im = ax.imshow(data, cmap="cividis", vmin=0.0, vmax=1.0, aspect="auto")
    ax.set_xticks(range(len(MODELS)))
    ax.set_xticklabels([MODEL_LABEL[m] for m in MODELS], rotation=30, ha="right", fontsize=8)
    ax.set_yticks(range(len(SCEN)))
    ax.set_yticklabels([SCEN_LABEL[s] for s in SCEN], fontsize=8)
    for i in range(len(SCEN)):
        for j in range(len(MODELS)):
            v = data[i][j]
            ax.text(j, i, f"{v:.1f}", ha="center", va="center", fontsize=8,
                    color="white" if v < 0.5 else "black")
    cb = fig.colorbar(im, ax=ax, fraction=0.046, pad=0.02)
    cb.set_label("Attack success rate (guardrails off)", fontsize=8)
    fig.savefig(path)
    plt.close(fig)
    return path


def write_factorial_table(factorial_path, out_dir):
    recs = [json.loads(l) for l in open(factorial_path) if l.strip()]

    def mean(scenario, prompt, controls):
        xs = [1 if r["asr_filtered"] else 0 for r in recs
              if r["scenario"] == scenario and r["prompt"] == prompt and r["controls"] == controls]
        return sum(xs) / len(xs) if xs else 0.0

    # columns: guardrails off (weak), hardened prompt only, structural P2+P5 (weak), all five
    cols = [("weak", "off"), ("hardened", "off"), ("weak", "struct"), ("hardened", "all")]
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "factorial.tex")
    lines = [
        "% Generated by scripts/make_figures.py -- do not edit by hand.",
        r"\begin{tabular}{@{}lcccc@{}}",
        r"\toprule",
        r" & Guardrails & Hardened & Structural & All five \\",
        r"Scenario & off & prompt only & (P2, P5) & controls \\",
        r"\midrule",
    ]
    for s in SCEN:
        vals = [mean(s, p, c) for p, c in cols]
        lines.append(f"{SCEN_LABEL[s]} & " + " & ".join(f"{v:.2f}" for v in vals) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    open(path, "w").write("\n".join(lines))
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", required=True)
    ap.add_argument("--factorial", required=True)
    ap.add_argument("--tables", default="tables")
    ap.add_argument("--figures", default="figures")
    ap.add_argument("--no-heatmap", action="store_true")
    args = ap.parse_args()
    print("factorial table:", write_factorial_table(args.factorial, args.tables))
    if not args.no_heatmap:
        print("heatmap:", make_heatmap(args.summary, args.figures))


if __name__ == "__main__":
    main()
