#!/usr/bin/env python3
"""Generate the paper's results artifacts from a benchmark summary.json.

Reads the rag-sec benchmark's summary.json (the `by_model_scenario_mode` rows)
and writes:

  tables/results.tex   a compact per-model summary (mean vulnerable vs secure
                       ASR, mean vulnerable refusal rate) as a booktabs table;
  figures/asr-heatmap.pdf  two heatmaps (vulnerable | secure) of ASR over
                       scenarios x models, viridis, value-annotated.

Usage:
  python3 scripts/make_figures.py --summary ../rag-sec/results/summary.json \
      --tables tables --figures figures

The table generator is pure-stdlib; only the heatmap needs matplotlib.
"""

import argparse
import json
import os

SCENARIO_LABEL = {
    "S1": "S1 LLM01 direct",
    "S2": "S2 LLM01 indirect",
    "S3": "S3 LLM02/08 leakage",
    "S4": "S4 LLM06 tool abuse",
    "S5": "S5 LLM07 prompt leak",
    "S6": "S6 LLM05 output",
}


def load_rows(summary_path: str) -> list[dict]:
    with open(summary_path, encoding="utf-8") as fh:
        return json.load(fh)["by_model_scenario_mode"]


def _ordered(values, preferred):
    """Preferred order first (those present), then any extras seen, stably."""
    seen = list(dict.fromkeys(values))
    head = [v for v in preferred if v in seen]
    tail = [v for v in seen if v not in head]
    return head + tail


def _grid(rows):
    models = _ordered([r["model_label"] for r in rows],
                      ["stub", "llama31-8b", "qwen25-7b", "mistral-7b", "gemma3-12b", "phi4-14b"])
    scenarios = _ordered([r["scenario"] for r in rows], ["S1", "S2", "S3", "S4", "S5", "S6"])
    asr = {(r["model_label"], r["scenario"], r["mode"]): r["attack_success_rate"] for r in rows}
    return models, scenarios, asr


def _mean(values):
    vals = [v for v in values if v is not None]
    return sum(vals) / len(vals) if vals else None


def write_results_table(rows, out_dir: str) -> str:
    models, scenarios, asr = _grid(rows)
    refusal = {(r["model_label"], r["scenario"], r["mode"]): r["refusal_rate"] for r in rows}
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "results.tex")

    def fmt(x):
        return "--" if x is None else f"{x:.2f}"

    lines = [
        "% Generated by scripts/make_figures.py — do not edit by hand.",
        r"\begin{tabular}{@{}lccc@{}}",
        r"\toprule",
        r"Model & Vuln.\ ASR & Secure ASR & Vuln.\ refusal \\",
        r"\midrule",
    ]
    for m in models:
        vuln_asr = _mean([asr.get((m, s, "vulnerable")) for s in scenarios])
        sec_asr = _mean([asr.get((m, s, "secure")) for s in scenarios])
        vuln_ref = _mean([refusal.get((m, s, "vulnerable")) for s in scenarios])
        lines.append(f"{m} & {fmt(vuln_asr)} & {fmt(sec_asr)} & {fmt(vuln_ref)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return path


def make_heatmap(rows, out_dir: str) -> str:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    models, scenarios, asr = _grid(rows)
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "asr-heatmap.pdf")

    def matrix(mode):
        return [[(asr.get((m, s, mode)) if asr.get((m, s, mode)) is not None else float("nan"))
                 for m in models] for s in scenarios]

    fig, axes = plt.subplots(1, 2, figsize=(7.0, 3.2), constrained_layout=True)
    last_im = None
    for ax, mode, title in zip(axes, ("vulnerable", "secure"),
                               ("Guardrails off (baseline)", "Gateway on")):
        data = matrix(mode)
        last_im = ax.imshow(data, cmap="viridis", vmin=0.0, vmax=1.0, aspect="auto")
        ax.set_xticks(range(len(models)))
        ax.set_xticklabels(models, rotation=45, ha="right", fontsize=8)
        ax.set_yticks(range(len(scenarios)))
        ax.set_yticklabels([SCENARIO_LABEL.get(s, s) for s in scenarios], fontsize=8)
        ax.set_title(title, fontsize=9)
        for i in range(len(scenarios)):
            for j in range(len(models)):
                v = data[i][j]
                if v == v:  # not NaN
                    ax.text(j, i, f"{v:.2f}", ha="center", va="center",
                            color="white" if v < 0.5 else "black", fontsize=7)
    cbar = fig.colorbar(last_im, ax=axes, fraction=0.046, pad=0.02)
    cbar.set_label("Attack success rate", fontsize=8)
    fig.savefig(path)
    plt.close(fig)
    return path


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate paper results table + heatmap")
    parser.add_argument("--summary", required=True, help="path to benchmark summary.json")
    parser.add_argument("--tables", default="tables")
    parser.add_argument("--figures", default="figures")
    parser.add_argument("--no-heatmap", action="store_true", help="skip the matplotlib figure")
    args = parser.parse_args()

    rows = load_rows(args.summary)
    print("table:", write_results_table(rows, args.tables))
    if not args.no_heatmap:
        print("figure:", make_heatmap(rows, args.figures))


if __name__ == "__main__":
    main()
