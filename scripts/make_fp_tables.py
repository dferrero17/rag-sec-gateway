#!/usr/bin/env python3
"""Regenerate fpnumbers.tex and tables/fp_v2.tex from the expanded false-positive
and entitled-user sweep (results_full/fp_v2.jsonl in the rag-sec tool repo).

Usage: python3 scripts/make_fp_tables.py [path/to/fp_v2.jsonl]
"""
import json, sys, collections, os, re

SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    os.path.dirname(__file__), "..", "..", "rag-sec", "results_full", "fp_v2.jsonl")
NAMES = {"llama31-8b": "Llama 3.1 8B", "qwen25-7b": "Qwen2.5 7B", "mistral-7b": "Mistral 7B",
         "gemma3-12b": "Gemma 3 12B", "phi4-14b": "Phi-4 14B", "stub": "Stub"}
ORDER = ["llama31-8b", "qwen25-7b", "mistral-7b", "gemma3-12b", "phi4-14b"]

rows = [json.loads(l) for l in open(SRC)]
p1 = [r for r in rows if r.get("kind") == "p1"]
p4 = [r for r in rows if r.get("kind") == "p4" and r.get("model") in ORDER]
util = [r for r in rows if r.get("kind") == "utility"]

n = len(p1)
near = [r for r in p1 if r.get("near_miss")]
p1_fp = [r for r in p1 if r.get("p1_blocked") or r.get("blocked")]
p1_fp_near = [r for r in p1_fp if r.get("near_miss")]

by_model = collections.defaultdict(list)
for r in p4:
    by_model[r["model"]].append(r)

def fmt_int(x):
    return f"{x:,}".replace(",", "{,}")

lines = ["% Generated by scripts/make_fp_tables.py from results_full/fp_v2.jsonl -- do not edit by hand.",
         r"\begin{tabular}{@{}lcccc@{}}", r"\toprule",
         r"Model & Answers & P4 altered & P4 on near-misses & Errors \\", r"\midrule"]
tot_runs = tot_red = tot_err = tot_red_near = 0
red_models = []
for m in ORDER:
    rs = by_model.get(m, [])
    ok = [r for r in rs if not r.get("error") and not r.get("blocked")]  # blocked by P1: no answer to redact
    err = sum(1 for r in rs if r.get("error"))
    red = [r for r in ok if r.get("redacted")]
    red_near = [r for r in red if r.get("near_miss")]
    tot_runs += len(ok); tot_red += len(red); tot_err += err; tot_red_near += len(red_near)
    if red:
        red_models.append((m, len(red), len(ok)))
    lines.append(f"{NAMES[m]} & {len(ok)} & {len(red)} & {len(red_near)} & {err} \\\\")
lines += [r"\midrule", f"All five & {tot_runs} & {tot_red} & {tot_red_near} & {tot_err} \\\\", r"\bottomrule", r"\end{tabular}"]
os.makedirs("tables", exist_ok=True)
open("tables/fp_v2.tex", "w").write("\n".join(lines) + "\n")

# Utility check: entitled principal vs public-only user, per model.
u_ent = [r for r in util if r.get("entitled") and r.get("model") in ORDER + ["stub"] and not r.get("error")]
u_pub = [r for r in util if not r.get("entitled") and r.get("model") in ORDER + ["stub"] and not r.get("error")]
uq = sorted({r["uid"] for r in util})
ent_retr = sum(1 for r in u_ent if r.get("restricted_retrieved"))
ent_ans = sum(1 for r in u_ent if r.get("marker_in_final"))
ent_raw = sum(1 for r in u_ent if r.get("marker_in_raw"))
ent_red = sum(1 for r in u_ent if r.get("redacted"))
YEAR_MISSES = {("mistral-7b", "u02"), ("mistral-7b", "u04"), ("gemma3-12b", "u02"),
               ("gemma3-12b", "u04"), ("phi4-14b", "u04")}  # hand-read: model declared the year unavailable
def _cat(r):
    e = r.get("answer_excerpt") or ""
    if "CALL send_email" in e or "send_email tool" in e: return "tool"
    if (r.get("model"), r.get("uid")) in YEAR_MISSES: return "year"
    return "refusal"
misses = [r for r in u_ent if r.get("restricted_retrieved") and not r.get("marker_in_raw")]
cats = collections.Counter(_cat(r) for r in misses)
ent_refused = cats["refusal"]
ent_tool = cats["tool"]; ent_year = cats["year"]
ent_delivered = sum(1 for r in u_ent if r.get("marker_in_raw"))
ref_by_model = collections.Counter(r["model"] for r in misses if _cat(r) == "refusal")
refnote = ("all on " + NAMES.get(next(iter(ref_by_model)), "") if len(ref_by_model) == 1 else
           "; ".join(f"{NAMES.get(m, m)}: {k}" for m, k in sorted(ref_by_model.items(), key=lambda x: -x[1])))
pub_retr = sum(1 for r in u_pub if r.get("restricted_retrieved"))
models_done = sorted({r["model"] for r in util})

p1note = ""
if p1_fp:
    p1note = (r"\footnote{The rejected questions were: " +
              "; ".join("``" + r["text"].replace("&", r"\&") + "''" for r in p1_fp[:6]) + ".}")
p4note = ""
if red_models:
    p4note = " (" + ", ".join(f"{NAMES[m]}: {k} of {t}" for m, k, t in red_models) + ")"
utilnote = ""
if ent_ans < ent_retr:
    utilnote = (f" (in {ent_raw} the model's raw answer carried it and in {ent_red} output redaction "
                f"masked a secret shape before release)")

macros = {
    "fpN": str(n), "fpNearMiss": str(len(near)),
    "fpPoneCount": str(len(p1_fp)), "fpPoneNote": p1note,
    "fpPfourTotal": str(tot_red), "fpPfourRuns": fmt_int(tot_runs), "fpPfourNote": p4note,
    "fpUtilN": str(len(uq)), "fpUtilRuns": str(len(u_ent)), "fpUtilRetrieved": str(ent_retr),
    "fpUtilAnswered": str(ent_ans), "fpUtilNote": utilnote,
    "fpUtilRedacted": str(ent_red), "fpUtilRefused": str(ent_refused), "fpUtilRefusedByModel": refnote,
    "fpUtilTool": str(ent_tool), "fpUtilYear": str(ent_year), "fpUtilDelivered": str(ent_delivered),
}
out = ["% Generated by scripts/make_fp_tables.py from results_full/fp_v2.jsonl -- do not edit by hand."]
out += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
open("fpnumbers.tex", "w").write("\n".join(out) + "\n")
print(f"benign n={n} near={len(near)} P1 fp={len(p1_fp)} (near {len(p1_fp_near)})")
for r in p1_fp: print("   P1 FP:", r.get("qid"), r.get("domain"), r.get("text"), "|", r.get("patterns"))
print(f"P4 runs={tot_runs} redacted={tot_red} errors={tot_err} models={sorted(by_model)}")
print(f"utility: models={models_done} q={len(uq)} entitled runs={len(u_ent)} retrieved={ent_retr} "
      f"marker_final={ent_ans} marker_raw={ent_raw} redacted={ent_red}; public retrieved={pub_retr}/{len(u_pub)}")
for r in u_ent:
    if r.get("redacted") or not r.get("marker_in_final"):
        print("   ent:", r["model"], r["uid"], r["restricted_doc"], "retr", r["restricted_retrieved"], "raw", r["marker_in_raw"], "final", r["marker_in_final"], "red", r["redacted"], r.get("redaction_patterns"))
